#!/usr/bin/env python3
"""Writes the simulation's arena-kit collision table from the pinned arena kit's descriptor.

The simulation never reads files at run time (determinism, the browser), so the collision
proxies of asset-tooling's `shooter-arena` kit (descriptor `arena-kit-descriptor-v1`, the
`arena-descriptor` attachment of `arena.floor`) become a checked-in Rust table,
`crates/shooter-sim/src/arena_kit/modules.rs`: one `Module` per kit module, its placement box
and its intact and broken collision proxies in integer centimetres. Run it after
`scripts/fetch-robot-kit.sh` whenever `assets/arena-kit.pin.json` is bumped;
`cargo test -p shooter-client --test arena` checks the table against the pinned kit.

    scripts/gen-arena-kit.py [ARENA_DIR]   # default target/arena-kit
"""

import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "shooter-sim", "src", "arena_kit", "modules.rs")
PIN = os.path.join(ROOT, "assets", "arena-kit.pin.json")
DESCRIPTOR = "arena-descriptor"
RISES = {"+X": "PosX", "-X": "NegX", "+Z": "PosZ", "-Z": "NegZ"}


def centimetres(metres, what):
    value = round(metres * 100)
    if abs(value - metres * 100) > 1e-6:
        sys.exit(f"{what}: {metres} m is not a whole centimetre")
    return value


def half(metres, what):
    value = round(metres * 50)
    if abs(value - metres * 50) > 1e-6:
        sys.exit(f"{what}: half of {metres} m is not a whole centimetre")
    return value


def variant_name(key):
    return "".join(part.capitalize() for part in key.removeprefix("arena.").split("-"))


def proxy(entry, key):
    what = f"{key} {entry['name']}"
    center = [centimetres(v, what) for v in entry["center"]]
    halves = [half(v, what) for v in entry["size"]]
    if entry["shape"] == "ramp":
        shape = f"Shape::Ramp(RampRise::{RISES[entry['rises']]})"
    elif entry["tag"] == "walkable":
        shape = "Shape::Walkable"
    elif entry["tag"] == "blocked":
        shape = "Shape::Blocked"
    elif entry["tag"] == "trigger":
        shape = "Shape::Trigger"
    else:
        sys.exit(f"{what}: unknown proxy {entry['shape']} {entry['tag']}")
    c = ", ".join(map(str, center))
    h = ", ".join(map(str, halves))
    return f'Proxy {{ name: "{entry["name"]}", center: [{c}], half: [{h}], shape: {shape} }}'


def main():
    directory = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "target", "arena-kit")
    pin = json.load(open(PIN))
    manifest_path = os.path.join(directory, "manifest.json")
    manifest_bytes = open(manifest_path, "rb").read()
    if hashlib.sha256(manifest_bytes).hexdigest() != pin["manifestSha256"]:
        sys.exit(f"{manifest_path} is not the pinned manifest (refetch: scripts/fetch-robot-kit.sh)")
    manifest = json.loads(manifest_bytes)
    attachment = None
    for asset in manifest["assets"]:
        if asset["key"] == "arena.floor" and asset["variant"] == "default":
            for item in asset.get("attachments", []):
                if item["name"] == DESCRIPTOR:
                    attachment = item
    if attachment is None:
        sys.exit("the kit has no arena-descriptor attachment")
    data = open(os.path.join(directory, attachment["path"]), "rb").read()
    if hashlib.sha256(data).hexdigest() != attachment["sha256"]:
        sys.exit("the arena descriptor is not its pinned content")
    descriptor = json.loads(data)
    if descriptor.get("schema") != "arena-kit-descriptor-v1":
        sys.exit(f"unexpected descriptor schema {descriptor.get('schema')}")

    assets = descriptor["assets"]
    names = [variant_name(asset["key"]) for asset in assets]
    lines = [
        "// @generated by scripts/gen-arena-kit.py from the pinned `shooter-arena` kit's descriptor",
        f"// (assets/arena-kit.pin.json, manifest {pin['manifestSha256']}).",
        "// Do not edit: rerun the script after bumping the pin.",
        "",
        "use super::{Proxy, Shape};",
        "use crate::physics::RampRise;",
        "",
        "/// The pinned kit's manifest SHA-256 this table was generated from.",
        f'pub const KIT_MANIFEST_SHA256: &str = "{pin["manifestSha256"]}";',
        "",
        "/// A module of the arena kit, in the descriptor's order.",
        "#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]",
        "pub enum Module {",
    ]
    for asset, name in zip(assets, names):
        note = asset["note"].replace("\n", " ")
        lines.append(f"    /// `{asset['key']}`: {note}")
        lines.append(f"    {name},")
    lines += [
        "}",
        "",
        "impl Module {",
        "    /// Every module, in the descriptor's order.",
        f"    pub const ALL: [Self; {len(assets)}] = [",
    ]
    lines += [f"        Self::{name}," for name in names]
    lines += [
        "    ];",
        "",
        "    /// Its kit key (`arena.…`), the bundle entry the clients draw.",
        "    #[must_use]",
        "    pub const fn key(self) -> &'static str {",
        "        match self {",
    ]
    lines += [f'            Self::{name} => "{asset["key"]}",' for asset, name in zip(assets, names)]
    lines += [
        "        }",
        "    }",
        "",
        "    /// Its placement box in its own frame (centimetres): `[min, max]`.",
        "    #[must_use]",
        "    pub const fn placement_box(self) -> [[i32; 3]; 2] {",
        "        match self {",
    ]
    for asset, name in zip(assets, names):
        lo = ", ".join(str(centimetres(v, asset["key"])) for v in asset["box"]["min"])
        hi = ", ".join(str(centimetres(v, asset["key"])) for v in asset["box"]["max"])
        lines.append(f"            Self::{name} => [[{lo}], [{hi}]],")
    lines += [
        "        }",
        "    }",
        "",
        "    /// Its intact collision proxies, in its own frame.",
        "    #[must_use]",
        "    pub const fn proxies(self) -> &'static [Proxy] {",
        "        match self {",
    ]
    for asset, name in zip(assets, names):
        items = ", ".join(proxy(entry, asset["key"]) for entry in asset["variants"]["default"]["collisionProxies"])
        lines.append(f"            Self::{name} => &[{items}],")
    lines += [
        "        }",
        "    }",
        "",
        "    /// Its broken variant's collision proxies, for the destructible modules.",
        "    #[must_use]",
        "    pub const fn broken_proxies(self) -> Option<&'static [Proxy]> {",
        "        match self {",
    ]
    for asset, name in zip(assets, names):
        broken = asset["variants"].get("broken")
        if broken:
            items = ", ".join(proxy(entry, asset["key"]) for entry in broken["collisionProxies"])
            lines.append(f"            Self::{name} => Some(&[{items}]),")
    lines += [
        "            _ => None,",
        "        }",
        "    }",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2024", OUT], check=True)
    print(f"{OUT}: {len(assets)} modules")


if __name__ == "__main__":
    main()
